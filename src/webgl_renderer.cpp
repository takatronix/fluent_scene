    // Mirrors changed atlas pages: new pages whole, existing ones as their
    // dirty row band. Uploads land before the replay; the rows written hold
    // only glyphs new this frame (pages used this frame are never evicted),
    // so the frame's earlier draws are unaffected.
    void syncPages() {
        detail::GlyphAtlas& atlas = text.atlas();
        for (size_t i = 0; i < atlas.pageCount(); ++i) {
            const auto& page = atlas.page(i);
            if (i < page_rev.size() && page_rev[i] == page.revision) {
                continue;
            }
            bool fresh = false;
            if (i >= page_tex.size()) {
                page_tex.push_back(createTex(static_cast<int>(page.size),
                                             static_cast<int>(page.size), Fmt::R8));
                page_rev.push_back(0);
                fresh = true;
            }
            int y0 = page.dirty_y0, y1 = page.dirty_y1;
            if (fresh || y1 <= y0) {
                y0 = 0;
                y1 = static_cast<int>(page.size);
            }
            uploadTex(page_tex[i], y0, y1 - y0,
                      page.px.data() + static_cast<size_t>(y0) * page.size);
            page_rev[i] = page.revision;
            atlas.clearDirty(i);
        }
    }

    static std::string boxLabel(const Box& box) {
        std::string label = box.label;
        if (box.score > 0) {
            char score[16];
            std::snprintf(score, sizeof score, "%.2f", box.score);
            label += (label.empty() ? "" : " ") + std::string(score);
        }
        return label;
    }

    // Pre-pass: gather polygon points and upload image content — all before
    // the replay.
    void prepassLayer(const Layer& layer) {
        if (layer.hidden()) {
            return;
        }
        const Content& content = layer.content();
        if (const auto* p = std::get_if<PolygonContent>(&content)) {
            if (layer.thickness() <= 0 && p->points.size() >= 3) {
                polygon_offsets[&layer] = static_cast<uint32_t>(polygon_points.size());
                polygon_points.insert(polygon_points.end(), p->points.begin(), p->points.end());
            }
        } else if (const auto* img = std::get_if<ImageContent>(&content)) {
            if (img->view.valid()) {
                uploadContentImage(img->view);
            }
        }
        // Filter image parameters (`lut` grades) ride the same upload path
        // and cache as image content; alpha is opaque, so the premultiply
        // staging is a no-op for them.
        for (const Filter& f : layer.filters()) {
            if (f.image.valid()) {
                uploadContentImage(f.image);
            }
        }
        if (layer.maskValue().valid()) {
            uploadContentImage(layer.maskValue());
        }
        for (const auto& child : layer.sublayers()) {
            prepassLayer(*child);
        }
    }

    void uploadContentImage(const ImageView& v) {
        auto& entry = image_cache[v.pixels];
        if (entry.frame_used == frame_counter) {
            return;  // shared source already transferred this frame
        }
        if (entry.tex.w != static_cast<int>(v.width) ||
            entry.tex.h != static_cast<int>(v.height)) {
            destroyTex(entry.tex);
            entry.tex = createTex(static_cast<int>(v.width), static_cast<int>(v.height),
                                  Fmt::RGBA8);
        }
        entry.frame_used = frame_counter;
        // Premultiply during staging so bilinear filtering matches the CPU
        // reference (which premultiplies per tap before interpolating).
        const uint32_t stride = v.stride();
        std::vector<uint8_t> premul(static_cast<size_t>(v.width) * v.height * 4);
        for (uint32_t y = 0; y < v.height; ++y) {
            const uint8_t* src = v.pixels + static_cast<size_t>(y) * stride;
            uint8_t* dst = premul.data() + static_cast<size_t>(y) * v.width * 4;
            for (uint32_t x = 0; x < v.width; ++x) {
                const uint8_t a = src[x * 4 + 3];
                dst[x * 4 + 0] = static_cast<uint8_t>(src[x * 4 + 0] * a / 255);
                dst[x * 4 + 1] = static_cast<uint8_t>(src[x * 4 + 1] * a / 255);
                dst[x * 4 + 2] = static_cast<uint8_t>(src[x * 4 + 2] * a / 255);
                dst[x * 4 + 3] = a;
            }
        }
        uploadTex(entry.tex, premul.data(), v.width * 4);
    }

