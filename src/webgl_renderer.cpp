// webgl_renderer.cpp — the WebGL2 backend, WebGPURenderer's twin for
// browsers that expose no WebGPU adapter but run WebGL2 on the GPU.
//
// Structure mirrors webgpu_renderer.cpp draw-for-draw (and thus the Vulkan
// backend and the CPU reference): the shared plan (render_shared.hpp) makes
// the same offscreen decisions and extents, the shared shape/filter bodies
// run as GLSL ES 3.00 machine-translated from the very SPIR-V the WebGPU
// backend translates to WGSL (wasm/build.sh --webgl: glslc -DFS_WEBGPU
// -DFS_WEBGL → naga --keep-coordinate-space; never hand-ported), coverage
// masks union multi-part content with MAX blending, and the four blend
// modes are the same fixed-function equations. What differs is WebGL's
// reality:
//
//  - recording vs. executing: GL runs commands as they are issued, so the
//    draws are RECORDED like a WebGPU command encoder (target switches and
//    draws with their 128-byte constant slots), the constants go up in one
//    buffer upload, and the list replays — one upload per frame instead of
//    one per draw, and texture uploads (images, glyph pages, polygon
//    points) land before any draw exactly as WebGPU's queue writes do.
//  - push constants → the group-1 uniform block of FS_WEBGPU, bound per
//    draw with glBindBufferRange (256-byte slots).
//  - polygon points: no storage buffers in WebGL2 → an RG32F texture,
//    1024 points per row (shape_mask.frag under FS_WEBGL).
//  - row order: every offscreen target keeps the top-left row order of the
//    other backends (naga --keep-coordinate-space: gl_FragCoord.y = pixel
//    row); only the present into the canvas flips (fullscreen.vert under
//    FS_FLIP_Y), since WebGL's default framebuffer starts bottom-left.
//  - float targets need EXT_color_buffer_float (rgba16f/r16f/rg16f, and
//    rgba32f for stateful filters); without it the context is refused and
//    the host keeps the CPU renderer.
//  - programs compile on first use (the filter program is large; a scene
//    without filters never pays for it).

