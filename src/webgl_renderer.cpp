// The per-draw constant block — must match push_common.glsl exactly
// (VulkanRenderer::Push under another delivery mechanism).
struct Push {
    float rect[4];
    float meta[4];
    float inv0[4];
    float inv1[4];
    float pa[4];
    float pb[4];
    float px2[4];
    float color[4];
};
static_assert(sizeof(Push) == 128, "constant block must match push_common.glsl");

void setInv(Push& p, const Mat23& inv) {
    p.inv0[0] = inv.a;
    p.inv0[1] = inv.c;
    p.inv0[2] = inv.tx;
    p.inv1[0] = inv.b;
    p.inv1[1] = inv.d;
    p.inv1[2] = inv.ty;
}

void setRect(Push& p, IRect r) {
    p.rect[0] = static_cast<float>(r.x0);
    p.rect[1] = static_cast<float>(r.y0);
    p.rect[2] = static_cast<float>(r.x1 - r.x0);
    p.rect[3] = static_cast<float>(r.y1 - r.y0);
}

void setColor(Push& p, Color c) {
    p.color[0] = c.r;
    p.color[1] = c.g;
    p.color[2] = c.b;
    p.color[3] = c.a;
}

// Texture formats the backend uses (WebGPU's names, GL's triples).
enum class Fmt { RGBA16F, RG16F, R16F, RGBA32F, RG32F, RGBA8, R8 };

struct GlFormat {
    GLenum internal, format, type;
};

GlFormat glFormat(Fmt f) {
    switch (f) {
        case Fmt::RGBA16F: return {GL_RGBA16F, GL_RGBA, GL_HALF_FLOAT};
        case Fmt::RG16F: return {GL_RG16F, GL_RG, GL_HALF_FLOAT};
        case Fmt::R16F: return {GL_R16F, GL_RED, GL_HALF_FLOAT};
        case Fmt::RGBA32F: return {GL_RGBA32F, GL_RGBA, GL_FLOAT};
        case Fmt::RG32F: return {GL_RG32F, GL_RG, GL_FLOAT};
        case Fmt::RGBA8: return {GL_RGBA8, GL_RGBA, GL_UNSIGNED_BYTE};
        case Fmt::R8: return {GL_R8, GL_RED, GL_UNSIGNED_BYTE};
    }
    return {GL_RGBA8, GL_RGBA, GL_UNSIGNED_BYTE};
}

// Blend codes of a pipeline: 0..3 = Blend modes, kOverwrite, kMax.
constexpr int kOverwrite = -1;
constexpr int kMax = -2;

