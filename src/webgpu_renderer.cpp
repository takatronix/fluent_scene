// The per-draw constant block — must match push_common.glsl exactly
// (VulkanRenderer::Push under another delivery mechanism).
struct Push {
    float rect[4];
    float meta[4];
    float inv0[4];
    float inv1[4];
    float pa[4];
    float pb[4];
    float px2[4];
    float color[4];
};
static_assert(sizeof(Push) == 128, "constant block must match push_common.glsl");

void setInv(Push& p, const Mat23& inv) {
    p.inv0[0] = inv.a;
    p.inv0[1] = inv.c;
    p.inv0[2] = inv.tx;
    p.inv1[0] = inv.b;
    p.inv1[1] = inv.d;
    p.inv1[2] = inv.ty;
}

void setRect(Push& p, IRect r) {
    p.rect[0] = static_cast<float>(r.x0);
    p.rect[1] = static_cast<float>(r.y0);
    p.rect[2] = static_cast<float>(r.x1 - r.x0);
    p.rect[3] = static_cast<float>(r.y1 - r.y0);
}

void setColor(Push& p, Color c) {
    p.color[0] = c.r;
    p.color[1] = c.g;
    p.color[2] = c.b;
    p.color[3] = c.a;
}

std::string toString(WGPUStringView s) {
    return s.data == nullptr ? std::string()
                             : (s.length == WGPU_STRLEN ? std::string(s.data)
                                                        : std::string(s.data, s.length));
}

WGPUStringView view(const char* s) { return {s, WGPU_STRLEN}; }

