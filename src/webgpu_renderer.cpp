// webgpu_renderer.cpp — the browser GPU backend (§11, Phase W3).
//
// Structure mirrors vulkan_renderer.cpp draw-for-draw: the shared plan
// (render_shared.hpp) makes the same offscreen decisions and extents, the
// shared shape/filter bodies run as WGSL machine-translated from the very
// SPIR-V the Vulkan backend embeds (wasm/build.sh --webgpu; never
// hand-ported), coverage masks union multi-part content with MAX blending,
// and the four blend modes are the same fixed-function equations. What
// differs is only the browser's reality:
//
//  - push constants → one uniform buffer, 256-byte slots, dynamic offsets
//    (group 1; group 0 keeps the texture/sampler or storage bindings).
//  - float32 render targets are not blendable in core WebGPU → the working
//    targets are rgba16float/r16float. Half precision is far inside the
//    golden tolerance for anything the compositor computes.
//  - no clamp-to-border sampler → composite.frag emulates the transparent
//    border under FS_WEBGPU (exact bilinear ramp; see the shader).
//  - no blocking readback → the primary path presents into the canvas
//    (present.frag, canvas alphaMode "premultiplied" — pixel-equal to the
//    CPU path's putImageData compositing); pixel comparison goes through
//    the async readbackBegin/readbackPixels pair instead.
//  - device acquisition is async → construction starts the request chain
//    and the host polls status() until Ready.

