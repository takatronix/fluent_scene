    void endTarget() {
        if (bound_target != nullptr) {
            wgpuRenderPassEncoderEnd(pass);
            wgpuRenderPassEncoderRelease(pass);
            pass = nullptr;
            bound_target = nullptr;
        }
    }

    // Begins (or resumes with load) rendering into `img` — the WebGPU form
    // of Vulkan's suspend/resume dynamic rendering, so offscreen subtrees
    // can render mid-parent in the CPU recursion order.
    void ensureTarget(Tex& img) {
        if (bound_target == &img) {
            return;
        }
        endTarget();
        beginPass(img.view, img.needs_clear);
        img.needs_clear = false;
        bound_target = &img;
    }

    void beginPass(WGPUTextureView target_view, bool clear) {
        WGPURenderPassColorAttachment color = WGPU_RENDER_PASS_COLOR_ATTACHMENT_INIT;
        color.view = target_view;
        color.loadOp = clear ? WGPULoadOp_Clear : WGPULoadOp_Load;
        color.storeOp = WGPUStoreOp_Store;
        color.clearValue = {0, 0, 0, 0};
        WGPURenderPassDescriptor rd = WGPU_RENDER_PASS_DESCRIPTOR_INIT;
        rd.colorAttachmentCount = 1;
        rd.colorAttachments = &color;
        pass = wgpuCommandEncoderBeginRenderPass(encoder, &rd);
    }

    WGPUBindGroup texGroup(WGPUTextureView tex_view, WGPUSampler sampler,
                           WGPUTextureView image_param_view = nullptr,
                           WGPUSampler image_param_sampler = nullptr,
                           WGPUTextureView state_view = nullptr) {
        // Bindings 2/3 carry a filter's image parameter, 4/5 a stateful
        // filter's field; without one the source self-binds so the group
        // is always complete.
        if (image_param_view == nullptr) {
            image_param_view = tex_view;
            image_param_sampler = sampler;
        }
        if (state_view == nullptr) {
            state_view = tex_view;
        }
        WGPUBindGroupEntry entries[6] = {WGPU_BIND_GROUP_ENTRY_INIT, WGPU_BIND_GROUP_ENTRY_INIT,
                                         WGPU_BIND_GROUP_ENTRY_INIT, WGPU_BIND_GROUP_ENTRY_INIT,
                                         WGPU_BIND_GROUP_ENTRY_INIT, WGPU_BIND_GROUP_ENTRY_INIT};
        entries[0].binding = 0;
        entries[0].textureView = tex_view;
        entries[1].binding = 1;
        entries[1].sampler = sampler;
        entries[2].binding = 2;
        entries[2].textureView = image_param_view;
        entries[3].binding = 3;
        entries[3].sampler = image_param_sampler;
        entries[4].binding = 4;
        entries[4].textureView = state_view;
        entries[5].binding = 5;
        entries[5].sampler = sampler_nearest;
        WGPUBindGroupDescriptor bd = {};
        bd.layout = bgl_tex;
        bd.entryCount = 6;
        bd.entries = entries;
        WGPUBindGroup g = wgpuDeviceCreateBindGroup(device, &bd);
        frame_groups.push_back(g);
        return g;
    }

    // One 256-byte slot in the push arena; contents reach the GPU via the
    // pre-submit writeBuffer in flushPushChunks().
    struct PushSlot {
        WGPUBindGroup group;
        uint32_t offset;
    };
    PushSlot allocPush(const Push& push) {
        if (push_chunks.empty() || push_chunks[push_chunk_i].used + kPushStride > kChunkBytes) {
            if (!push_chunks.empty()) {
                ++push_chunk_i;
            }
            if (push_chunk_i >= push_chunks.size()) {
                PushChunk c;
                c.buf = createBuffer(kChunkBytes,
                                     WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst);
                WGPUBindGroupEntry entry = WGPU_BIND_GROUP_ENTRY_INIT;
                entry.binding = 0;
                entry.buffer = c.buf;
                entry.size = sizeof(Push);
                WGPUBindGroupDescriptor bd = {};
                bd.layout = bgl_push;
                bd.entryCount = 1;
                bd.entries = &entry;
                c.group = wgpuDeviceCreateBindGroup(device, &bd);
                c.cpu.resize(kChunkBytes);
                push_chunks.push_back(std::move(c));
            }
        }
        PushChunk& c = push_chunks[push_chunk_i];
        std::memcpy(c.cpu.data() + c.used, &push, sizeof(Push));
        const uint32_t offset = c.used;
        c.used += kPushStride;
        return {c.group, offset};
    }

    void flushPushChunks() {
        for (PushChunk& c : push_chunks) {
            if (c.used > 0) {
                wgpuQueueWriteBuffer(queue, c.buf, 0, c.cpu.data(), c.used);
            }
        }
    }

    void drawQuad(WGPURenderPipeline pipeline, WGPUBindGroup group0, const Push& push) {
        wgpuRenderPassEncoderSetPipeline(pass, pipeline);
        wgpuRenderPassEncoderSetBindGroup(pass, 0, group0, 0, nullptr);
        const PushSlot slot = allocPush(push);
        wgpuRenderPassEncoderSetBindGroup(pass, 1, slot.group, 1, &slot.offset);
        wgpuRenderPassEncoderDraw(pass, 4, 1, 0, 0);
    }

    void drawFullscreen(WGPURenderPipeline pipeline, WGPUBindGroup group0, const Push& push) {
        wgpuRenderPassEncoderSetPipeline(pass, pipeline);
        wgpuRenderPassEncoderSetBindGroup(pass, 0, group0, 0, nullptr);
        const PushSlot slot = allocPush(push);
        wgpuRenderPassEncoderSetBindGroup(pass, 1, slot.group, 1, &slot.offset);
        wgpuRenderPassEncoderDraw(pass, 3, 1, 0, 0);
    }

    // ---- transient pool ----------------------------------------------------

    Tex* acquireTransient(int w, int h, WGPUTextureFormat format) {
        for (auto& t : transient_pool) {
            if (!t->in_use && t->w == w && t->h == h && t->format == format) {
                t->in_use = true;
                t->needs_clear = true;
                return t.get();
            }
        }
        transient_pool.push_back(std::make_unique<Tex>(createTex(
            w, h, format, WGPUTextureUsage_RenderAttachment | WGPUTextureUsage_TextureBinding)));
        transient_pool.back()->in_use = true;
        transient_pool.back()->needs_clear = true;
        return transient_pool.back().get();
    }

    void releaseAllTransients() {
        for (auto& t : transient_pool) {
            t->in_use = false;
        }
    }

    // ---- uploads (queue writes land before the frame's submit) -------------

    void uploadTex(Tex& t, const void* pixels, uint32_t bytes_per_row) {
        WGPUTexelCopyTextureInfo dst = WGPU_TEXEL_COPY_TEXTURE_INFO_INIT;
        dst.texture = t.tex;
        WGPUTexelCopyBufferLayout layout = {};
        layout.bytesPerRow = bytes_per_row;
        layout.rowsPerImage = static_cast<uint32_t>(t.h);
        WGPUExtent3D size = {static_cast<uint32_t>(t.w), static_cast<uint32_t>(t.h), 1};
        wgpuQueueWriteTexture(queue, &dst, pixels,
                              static_cast<size_t>(bytes_per_row) * t.h, &layout, &size);
    }

